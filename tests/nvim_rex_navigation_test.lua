local root = assert(os.getenv("NVIM_TYPST_TEST_ROOT"))
package.path = root .. "/dotfiles/.config/nvim/lua/?.lua;" .. package.path
local navigation = require("config.modules.rex-navigation")
assert(navigation.move("left") == "edge")
vim.cmd("vsplit")
local first = vim.api.nvim_get_current_win()
assert(navigation.move("right") == "moved")
assert(vim.api.nvim_get_current_win() ~= first)
assert(navigation.move("right") == "edge")
assert(not pcall(navigation.move, "bad"))
print("Neovim Rex navigation tests passed")
vim.cmd("qa!")
